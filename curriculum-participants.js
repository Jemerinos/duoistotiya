  /* Remove a common regex false positive: the place name Constantinople must not imply emperor Constantine. */
  course.lessons.forEach(function (row) {
    var meta = row[6] || {}, depth = meta.depth || {};
    var text = [row[0], row[1], row[3], meta.detailedText || ""].join(" ");
    depth.people = (depth.people || []).filter(function (person) {
      if (person.name !== "Константин") return true;
      var explicit = /(?:император(?:а|ом)?\s+Константин|Константин\s+(?:I|Великий|первый))/i.test(text);
      return explicit || !/Константинополь/i.test(text);
    });
    meta.depth = depth;
    row[6] = meta;
  });

  var added = 0, mapped = [];
  Object.keys(byDay).forEach(function (key) {
    var day = Number(key), entry = byDay[key], row = course.lessons[day - 1];
    if (!row || row[0] !== entry.title) throw new Error("Participant map mismatch for lesson " + day);
    var meta = row[6] || {}, depth = meta.depth || (meta.depth = {});
    var people = Array.isArray(depth.people) ? depth.people.slice() : [];
    entry.people.forEach(function (person) {
      var exists = people.some(function (item) { return String(item.name).toLocaleLowerCase("ru") === person.name.toLocaleLowerCase("ru"); });
      if (!exists) { people.push(person); added++; }
    });
    depth.people = people;
    meta.depth = depth;
    row[6] = meta;
    mapped.push(day);
  });
